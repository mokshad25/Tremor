// Command eval replays TREMOR's labelled scenarios (exported by
// bench/eval/export_scenarios.py) through the Go detectors, scores them
// with the Python harness's matching rule, and compares every alert with
// what the Python implementation raised on the same input.
package main

import (
	"context"
	"flag"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"time"

	"github.com/mokshad/tremor/internal/detect"
	"github.com/mokshad/tremor/internal/eval"
	"github.com/mokshad/tremor/internal/redact"
	"github.com/mokshad/tremor/internal/sim"
	"github.com/mokshad/tremor/internal/summarize"
)

func main() {
	dir := flag.String("scenarios", "bench/eval/scenarios", "directory of exported scenarios")
	out := flag.String("out", "", "also write the markdown report here")
	grace := flag.Float64("grace", eval.DefaultGrace, "matching grace (seconds)")
	warmup := flag.Int("warmup-ticks", 0, "override detect warmup_ticks (0 = default)")
	security := flag.Bool("security", false, "run the security-rule evaluation (attack simulator) instead")
	sshLog := flag.String("ssh", "", "replay a Loghub OpenSSH log (e.g. bench/data/OpenSSH_2k.log) through redaction + rules")
	year := flag.Int("year", 2017, "year for syslog timestamps (they carry none)")
	summaries := flag.String("summaries", "", "write LLM incident summaries + a scoring sheet for every scenario into this directory (uses TREMOR_LLM_API_KEY if set)")
	model := flag.String("model", summarize.DefaultLLMConfig().Model, "LLM model for -summaries")
	flag.Parse()
	if *summaries != "" {
		lcfg := summarize.DefaultLLMConfig()
		lcfg.RatePerMinute = 0 // the harness paces its own calls
		var llm summarize.Summarizer
		if key := os.Getenv("TREMOR_LLM_API_KEY"); key != "" {
			llm = &summarize.OpenAICompatible{Endpoint: lcfg.Endpoint, Model: *model, APIKey: key, MaxTokens: lcfg.MaxTokens,
				HTTP: &http.Client{Timeout: 60 * time.Second}}
			fmt.Fprintf(os.Stderr, "summaries: %s via %s\n", *model, lcfg.Endpoint)
		} else {
			fmt.Fprintln(os.Stderr, "summaries: TREMOR_LLM_API_KEY not set, template summaries only")
		}
		g := summarize.NewGuarded(llm, lcfg, redact.New(eval.EvalKey).String, nil)
		err := eval.GenerateSummaries(context.Background(), *summaries, *dir, g, func(s string) { fmt.Fprintln(os.Stderr, s) })
		if err != nil {
			fmt.Fprintln(os.Stderr, "eval:", err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "llm: %d ok, %d errors, %d invalid, %d fallbacks, %d prompt + %d completion tokens\n",
			g.Stats.OK.Load(), g.Stats.Errors.Load(), g.Stats.Invalid.Load(), g.Stats.Fallbacks.Load(),
			g.Stats.PromptTokens.Load(), g.Stats.CompletionTokens.Load())
		return
	}
	if *sshLog != "" {
		f, err := os.Open(*sshLog)
		if err != nil {
			fmt.Fprintln(os.Stderr, "eval:", err)
			os.Exit(1)
		}
		lines, skipped, err := sim.ReadSyslog(f, *year)
		f.Close()
		if err != nil {
			fmt.Fprintln(os.Stderr, "eval:", err)
			os.Exit(1)
		}
		report := "# Loghub OpenSSH replay\n\n> Generated by `go run ./cmd/eval -ssh " + *sshLog + "`.\n\n" +
			eval.SSHReplayReport(filepath.Base(*sshLog), lines, skipped, detect.DefaultConfig())
		fmt.Print(report)
		if *out != "" {
			if err := os.WriteFile(*out, []byte(report), 0o644); err != nil {
				fmt.Fprintln(os.Stderr, "eval:", err)
				os.Exit(1)
			}
		}
		return
	}
	if *security {
		attack, clean := sim.DefaultConfig(), sim.DefaultConfig()
		clean.Attacks, clean.Seed = false, 11
		rep := eval.EvaluateSecurity(attack, clean, detect.DefaultConfig())
		report := "# TREMOR at Scale: security detection evaluation\n\n> Generated by `go run ./cmd/eval -security`. Do not edit by hand.\n\n" + eval.SecurityMarkdown(rep, attack, clean)
		fmt.Print(report)
		if *out != "" {
			if err := os.WriteFile(*out, []byte(report), 0o644); err != nil {
				fmt.Fprintln(os.Stderr, "eval:", err)
				os.Exit(1)
			}
		}
		return
	}

	scenarios, err := eval.LoadAll(*dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "eval:", err)
		os.Exit(1)
	}
	cfg := detect.DefaultConfig()
	if *warmup > 0 {
		cfg.WarmupTicks = *warmup
	}
	runs := eval.Evaluate(scenarios, eval.Detectors(cfg), *grace)
	header := fmt.Sprintf("# TREMOR at Scale: detection evaluation\n\n> Generated by `go run ./cmd/eval` (warmup_ticks=%d). Do not edit by hand.", cfg.WarmupTicks)
	report := eval.Markdown(scenarios, runs, *grace, header)
	fmt.Print(report)
	if *out != "" {
		if err := os.WriteFile(*out, []byte(report), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "eval:", err)
			os.Exit(1)
		}
	}
}
